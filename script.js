const serviceOrder = ["window", "split", "fridge", "washer", "install"];
let currentLang = "ar";

function lookup(lang, key) {
  return key.split(".").reduce((obj, part) => (obj == null ? undefined : obj[part]), translations[lang]);
}

function waLink(number, text) {
  return `https://wa.me/${number}?text=${encodeURIComponent(text)}`;
}

function readLang() {
  try {
    const saved = localStorage.getItem("naqi-lang");
    if (saved === "ar" || saved === "en") return saved;
  } catch (err) {
    return "ar";
  }
  return "ar";
}

function saveLang(lang) {
  try {
    localStorage.setItem("naqi-lang", lang);
  } catch (err) {
    /* Storage can be blocked. The language still applies for this visit. */
  }
}

function fillServices(lang) {
  const select = document.querySelector("#service");
  const current = select.value;
  const form = translations[lang].form;
  select.replaceChildren();
  const placeholder = document.createElement("option");
  placeholder.value = "";
  placeholder.textContent = form.servicePlaceholder;
  select.appendChild(placeholder);
  serviceOrder.forEach((id) => {
    const option = document.createElement("option");
    option.value = id;
    option.textContent = translations[lang].services[id].title;
    select.appendChild(option);
  });
  select.value = serviceOrder.includes(current) ? current : "";
}

function applyLanguage(lang) {
  currentLang = lang;
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = lookup(lang, "meta.title");
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", lookup(lang, "meta.description"));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = lookup(lang, el.dataset.i18n);
    if (typeof value === "string") el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const value = lookup(lang, el.dataset.i18nPlaceholder);
    if (typeof value === "string") el.placeholder = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = lookup(lang, el.dataset.i18nAlt);
    if (typeof value === "string") el.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = lookup(lang, el.dataset.i18nAria);
    if (typeof value === "string") el.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-wa]").forEach((link) => {
    link.href = waLink(link.dataset.wa, lookup(lang, "wa.greeting"));
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.setLang === lang));
  });

  fillServices(lang);
  updateMenuLabel();
  saveLang(lang);
}

function updateMenuLabel() {
  const toggle = document.querySelector(".nav-toggle");
  const nav = document.querySelector("#site-nav");
  const open = nav.classList.contains("is-open");
  toggle.setAttribute("aria-expanded", String(open));
  toggle.setAttribute("aria-label", lookup(currentLang, open ? "nav.close" : "nav.menu"));
}

function closeNav() {
  document.querySelector("#site-nav").classList.remove("is-open");
  updateMenuLabel();
}

function setFloatOpen(open) {
  const panel = document.querySelector("#wa-panel");
  const button = document.querySelector(".wa-float-btn");
  panel.hidden = !open;
  button.setAttribute("aria-expanded", String(open));
  if (open) {
    const firstLink = panel.querySelector("a");
    if (firstLink) firstLink.focus();
  }
}

function selectedServiceLabel() {
  const id = document.querySelector("#service").value;
  if (!serviceOrder.includes(id)) return "";
  return translations[currentLang].services[id].title;
}

function validateForm(data) {
  const form = translations[currentLang].form;
  const errors = [];
  if (data.name.trim().length < 2) errors.push(form.errName);
  if (data.phone.replace(/\D/g, "").length < 9) errors.push(form.errPhone);
  if (!serviceOrder.includes(data.service)) errors.push(form.errService);
  return errors;
}

function buildMessage(data) {
  const form = translations[currentLang].form;
  const lines = [
    form.msgIntro,
    `${form.msgName}: ${data.name.trim()}`,
    `${form.msgPhone}: ${data.phone.trim()}`,
    `${form.msgService}: ${selectedServiceLabel()}`
  ];
  if (data.problem.trim()) lines.push(`${form.msgProblem}: ${data.problem.trim().slice(0, 500)}`);
  return lines.join("\n");
}

function openWhatsApp(number, text) {
  const url = waLink(number, text);
  const opened = window.open(url, "_blank", "noopener,noreferrer");
  if (!opened) window.location.href = url;
}

function init() {
  const header = document.querySelector(".site-header");
  const nav = document.querySelector("#site-nav");
  const toggle = document.querySelector(".nav-toggle");
  const float = document.querySelector("#wa-float");
  const form = document.querySelector("#request-form");
  const error = document.querySelector("#form-error");

  applyLanguage(readLang());

  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.setLang);
      closeNav();
    });
  });

  toggle.addEventListener("click", () => {
    nav.classList.toggle("is-open");
    updateMenuLabel();
  });
  nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeNav));

  document.querySelectorAll("[data-pick-service]").forEach((button) => {
    button.addEventListener("click", () => {
      const select = document.querySelector("#service");
      select.value = button.dataset.pickService;
      const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      document.querySelector("#contact").scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth" });
      document.querySelector("#customer-name").focus();
    });
  });

  document.querySelectorAll(".faq-item button").forEach((button) => {
    button.addEventListener("click", () => {
      const panel = document.getElementById(button.getAttribute("aria-controls"));
      const willOpen = panel.hidden;
      document.querySelectorAll(".faq-item").forEach((item) => {
        item.classList.remove("is-open");
        item.querySelector("button").setAttribute("aria-expanded", "false");
        item.querySelector("[role='region']").hidden = true;
      });
      if (willOpen) {
        panel.hidden = false;
        button.setAttribute("aria-expanded", "true");
        button.parentElement.classList.add("is-open");
      }
    });
  });

  document.querySelector(".wa-float-btn").addEventListener("click", () => {
    const panel = document.querySelector("#wa-panel");
    const willOpen = panel.hidden;
    setFloatOpen(willOpen);
  });

  document.addEventListener("click", (event) => {
    if (!float.contains(event.target)) setFloatOpen(false);
    if (!header.contains(event.target)) closeNav();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key !== "Escape") return;
    if (!document.querySelector("#wa-panel").hidden) {
      setFloatOpen(false);
      document.querySelector(".wa-float-btn").focus();
      return;
    }
    if (nav.classList.contains("is-open")) {
      closeNav();
      toggle.focus();
    }
  });

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const data = {
      name: document.getElementById("customer-name").value,
      phone: document.getElementById("customer-phone").value,
      service: document.getElementById("service").value,
      problem: document.getElementById("problem").value
    };
    const errors = validateForm(data);
    if (errors.length) {
      error.hidden = false;
      error.textContent = errors.join(" ");
      return;
    }
    error.hidden = true;
    const selected = form.querySelector('input[name="waNumber"]:checked');
    openWhatsApp(selected.value, buildMessage(data));
  });
}

init();
